-- Reconstructed schema-only baseline from the confirmed existing database.
-- No Auth users, profile content, Storage objects, or customer data are seeded.
-- IF NOT EXISTS makes replay on the existing database non-destructive. The next
-- migration replaces legacy policy/grant behavior with the lifecycle contract.
create table if not exists public.users_roles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  role text not null,
  created_at timestamptz default now()
);
create table if not exists public.profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  name text not null,
  title text,
  bio text,
  photo_url text,
  links jsonb,
  show_save_contact boolean,
  updated_at timestamptz,
  background text,
  created_at timestamptz default now()
);
create table if not exists public.nfc_items (
  id uuid primary key default gen_random_uuid(),
  slug text unique not null,
  product_type text not null,
  owner_id uuid not null references auth.users(id) on delete cascade,
  is_active boolean not null default true,
  created_at timestamptz default now()
);
create table if not exists public.tap_events (
  id bigint generated by default as identity primary key,
  nfc_item_id uuid not null references public.nfc_items(id) on delete set null,
  device_type text not null,
  referrer text,
  ip_hash text,
  created_at timestamptz default now()
);

-- Snapshot of the known public bucket; never overwrite its existing settings.
insert into storage.buckets (id, name, public)
values ('profile-photos', 'profile-photos', true) on conflict (id) do nothing;

alter table public.users_roles enable row level security;
alter table public.profiles enable row level security;
alter table public.nfc_items enable row level security;
alter table public.tap_events enable row level security;

-- Fresh-database legacy policies only. Existing deployment policies are retained
-- until the additive migration replaces them, independent of their old names.
create or replace function public.is_admin() returns boolean
language sql stable security definer set search_path = '' as $$
  select exists (select 1 from public.users_roles
    where user_id = (select auth.uid()) and role = 'admin');
$$;
do $$
begin
  if not exists (select 1 from pg_policies where schemaname='public' and tablename='users_roles') then
    create policy baseline_roles_read on public.users_roles for select to authenticated
      using (user_id = (select auth.uid()) or (select public.is_admin()));
  end if;
  if not exists (select 1 from pg_policies where schemaname='public' and tablename='profiles') then
    create policy baseline_profiles_read on public.profiles for select to authenticated
      using (user_id = (select auth.uid()) or (select public.is_admin()));
    create policy baseline_profiles_insert on public.profiles for insert to authenticated
      with check (user_id = (select auth.uid()));
    create policy baseline_profiles_update on public.profiles for update to authenticated
      using (user_id = (select auth.uid())) with check (user_id = (select auth.uid()));
  end if;
  if not exists (select 1 from pg_policies where schemaname='public' and tablename='nfc_items') then
    create policy baseline_items_read on public.nfc_items for select to authenticated
      using (owner_id = (select auth.uid()) or (select public.is_admin()));
    create policy baseline_items_update on public.nfc_items for update to authenticated
      using ((select public.is_admin())) with check ((select public.is_admin()));
  end if;
  if not exists (select 1 from pg_policies where schemaname='public' and tablename='tap_events') then
    create policy baseline_events_read on public.tap_events for select to authenticated
      using ((select public.is_admin()) or exists (select 1 from public.nfc_items i
        where i.id = nfc_item_id and i.owner_id = (select auth.uid())));
  end if;
end $$;
